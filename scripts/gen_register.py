"""Generate docs/STATUTORY_REGISTER.md from backend/app/rules/ng_2026_v1.yaml."""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "backend" / "app" / "rules" / "ng_2026_v1.yaml"
OUT = ROOT / "docs" / "STATUTORY_REGISTER.md"

STATUS_HELP = {
    "SECONDARY_VERIFIED": "Supported by at least one law-firm / practitioner summary of the gazetted Act. Primary text not read.",
    "CONFLICTING": "Sources disagree. The engine either needs a buyer policy or exposes a toggle; the default is stated.",
    "BRIEF_ONLY": "Taken from the build brief / enterprise brief only; no independent source located.",
    "UNVERIFIED": "Not located in any source we reviewed. Used only as a label, warning or hold — never to charge money.",
    "BUYER_POLICY": "The buyer's own AP control or engine invariant. Not law.",
}


def _val(v) -> str:
    if isinstance(v, dict):
        parts = []
        for k, x in v.items():
            parts.append(f"{k}: {x['rate'] if isinstance(x, dict) and 'rate' in x else x}"
                         + (f" ({x['status']})" if isinstance(x, dict) and "status" in x else ""))
        return "<br>".join(parts)
    return str(v).replace("|", "\\|")


def main() -> None:
    data = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    lines = [
        f"# Statutory register — `{data['pack']}`",
        "",
        f"_Generated by `scripts/gen_register.py` from `backend/app/rules/ng_2026_v1.yaml`. Effective date for the pack: {data['effective_date']}._",
        "",
        "> **Most rule citations come from law-firm and tax-practitioner summaries of the gazetted Acts; verify against the "
        "Official Gazette (No. 117, Vol. 112, 26 June 2025) before relying on them.** Nothing here is labelled "
        "VERIFIED_PRIMARY because the primary gazetted text was not read for these items. This is not tax advice.",
        "",
        "## Status labels",
        "",
        "| Status | Meaning |",
        "|---|---|",
        *[f"| `{k}` | {v} |" for k, v in STATUS_HELP.items()],
        "",
        "## Statutory rules",
        "",
        "| id | v | value | cite | status | note |",
        "|---|---|---|---|---|---|",
    ]
    for r in data["rules"]:
        lines.append(f"| `{r['id']}` | {r['version']} | {_val(r['value'])} | {r['cite']} | `{r['status']}` | "
                     f"{r['note'].replace('|', '/')} |")
    lines += ["", "## Buyer AP controls (not law)", "", "| id | rule | cite | status |", "|---|---|---|---|"]
    for r in data["controls"]:
        lines.append(f"| `{r['id']}` | {_val(r['value'])} | {r['cite']} | `{r['status']}` |")
    open_items = [r for r in data["rules"] if r["status"] in ("CONFLICTING", "UNVERIFIED", "BRIEF_ONLY")]
    lines += ["", "## Open items (CONFLICTING / UNVERIFIED / BRIEF_ONLY)", ""]
    lines += [f"- `{r['id']}` — **{r['status']}** — {r['note']}" for r in open_items]
    lines += ["- `WHT_RATES` (per category) — GOODS and CONSTRUCTION are **BRIEF_ONLY**; RENT is **CONFLICTING** (5% vs 10%, no default → POLICY_REQUIRED); OTHER → POLICY_REQUIRED.", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
